package support

import "strings"

const Part22Name = "indigo-part-22"

func Part22Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part22Name + "-empty-01"
	}
	return Part22Name + "-" + cleaned + "-01"
}

