import "strings"

const Part33Name = "indigo-part-33"

func Part33Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part33Name + "-empty-01"
	}
	return Part33Name + "-" + cleaned + "-01"
}

