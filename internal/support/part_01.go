package support

import "strings"

const Part01Name = "indigo-part-01"

func Part01Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part01Name + "-empty-01"
	}
	return Part01Name + "-" + cleaned + "-01"
}

