const Part23Name = "indigo-part-23"

func Part23Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part23Name + "-empty-01"
	}
	return Part23Name + "-" + cleaned + "-01"
}

