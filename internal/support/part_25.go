import "strings"

const Part25Name = "indigo-part-25"

func Part25Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part25Name + "-empty-01"
	}
	return Part25Name + "-" + cleaned + "-01"
}

