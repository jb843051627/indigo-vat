import "strings"

const Part31Name = "indigo-part-31"

func Part31Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part31Name + "-empty-01"
	}
	return Part31Name + "-" + cleaned + "-01"
}

