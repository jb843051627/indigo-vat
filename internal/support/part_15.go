package support

import "strings"

const Part15Name = "indigo-part-15"

func Part15Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part15Name + "-empty-01"
	}
	return Part15Name + "-" + cleaned + "-01"
}

