package support

import "strings"

const Part16Name = "indigo-part-16"

func Part16Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part16Name + "-empty-01"
	}
	return Part16Name + "-" + cleaned + "-01"
}

