const Part07Name = "indigo-part-07"

func Part07Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part07Name + "-empty-01"
	}
	return Part07Name + "-" + cleaned + "-01"
}

