package support

import "strings"

const Part10Name = "indigo-part-10"

func Part10Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part10Name + "-empty-01"
	}
	return Part10Name + "-" + cleaned + "-01"
}

