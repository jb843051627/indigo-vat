const Part39Name = "indigo-part-39"

func Part39Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part39Name + "-empty-01"
	}
	return Part39Name + "-" + cleaned + "-01"
}

