const Part06Name = "indigo-part-06"

func Part06Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part06Name + "-empty-01"
	}
	return Part06Name + "-" + cleaned + "-01"
}

