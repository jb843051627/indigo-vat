package support

import "strings"

const Part32Name = "indigo-part-32"

func Part32Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part32Name + "-empty-01"
	}
	return Part32Name + "-" + cleaned + "-01"
}

