package support

import "strings"

const Part17Name = "indigo-part-17"

func Part17Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part17Name + "-empty-01"
	}
	return Part17Name + "-" + cleaned + "-01"
}

