const Part08Name = "indigo-part-08"

func Part08Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part08Name + "-empty-01"
	}
	return Part08Name + "-" + cleaned + "-01"
}

