import "strings"

const Part36Name = "indigo-part-36"

func Part36Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part36Name + "-empty-01"
	}
	return Part36Name + "-" + cleaned + "-01"
}

