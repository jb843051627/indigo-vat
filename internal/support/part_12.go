package support

import "strings"

const Part12Name = "indigo-part-12"

func Part12Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part12Name + "-empty-01"
	}
	return Part12Name + "-" + cleaned + "-01"
}

