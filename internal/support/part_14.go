import "strings"

const Part14Name = "indigo-part-14"

func Part14Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part14Name + "-empty-01"
	}
	return Part14Name + "-" + cleaned + "-01"
}

