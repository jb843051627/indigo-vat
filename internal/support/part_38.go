import "strings"

const Part38Name = "indigo-part-38"

func Part38Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part38Name + "-empty-01"
	}
	return Part38Name + "-" + cleaned + "-01"
}

