package support

import "strings"

const Part40Name = "indigo-part-40"

func Part40Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part40Name + "-empty-01"
	}
	return Part40Name + "-" + cleaned + "-01"
}

