const Part42Name = "indigo-part-42"

func Part42Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part42Name + "-empty-01"
	}
	return Part42Name + "-" + cleaned + "-01"
}

