const Part02Name = "indigo-part-02"

func Part02Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part02Name + "-empty-01"
	}
	return Part02Name + "-" + cleaned + "-01"
}

