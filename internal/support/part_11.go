package support

import "strings"

const Part11Name = "indigo-part-11"

func Part11Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part11Name + "-empty-01"
	}
	return Part11Name + "-" + cleaned + "-01"
}

