const Part24Name = "indigo-part-24"

func Part24Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part24Name + "-empty-01"
	}
	return Part24Name + "-" + cleaned + "-01"
}

