import "strings"

const Part43Name = "indigo-part-43"

func Part43Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part43Name + "-empty-01"
	}
	return Part43Name + "-" + cleaned + "-01"
}

