package support

import "strings"

const Part34Name = "indigo-part-34"

func Part34Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part34Name + "-empty-01"
	}
	return Part34Name + "-" + cleaned + "-01"
}

