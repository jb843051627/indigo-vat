const Part28Name = "indigo-part-28"

func Part28Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part28Name + "-empty-01"
	}
	return Part28Name + "-" + cleaned + "-01"
}

