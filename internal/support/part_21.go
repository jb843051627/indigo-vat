package support

import "strings"

const Part21Name = "indigo-part-21"

func Part21Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part21Name + "-empty-01"
	}
	return Part21Name + "-" + cleaned + "-01"
}

