import "strings"

const Part26Name = "indigo-part-26"

func Part26Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part26Name + "-empty-01"
	}
	return Part26Name + "-" + cleaned + "-01"
}

