package support

import "strings"

const Part13Name = "indigo-part-13"

func Part13Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part13Name + "-empty-01"
	}
	return Part13Name + "-" + cleaned + "-01"
}

