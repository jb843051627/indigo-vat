import "strings"

const Part30Name = "indigo-part-30"

func Part30Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part30Name + "-empty-01"
	}
	return Part30Name + "-" + cleaned + "-01"
}

