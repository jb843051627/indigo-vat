const Part09Name = "indigo-part-09"

func Part09Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part09Name + "-empty-01"
	}
	return Part09Name + "-" + cleaned + "-01"
}

