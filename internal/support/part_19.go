import "strings"

const Part19Name = "indigo-part-19"

func Part19Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part19Name + "-empty-01"
	}
	return Part19Name + "-" + cleaned + "-01"
}

