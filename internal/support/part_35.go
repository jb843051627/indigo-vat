package support

import "strings"

const Part35Name = "indigo-part-35"

func Part35Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part35Name + "-empty-01"
	}
	return Part35Name + "-" + cleaned + "-01"
}

