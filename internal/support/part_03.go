const Part03Name = "indigo-part-03"

func Part03Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part03Name + "-empty-01"
	}
	return Part03Name + "-" + cleaned + "-01"
}

