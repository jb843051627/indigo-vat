import "strings"

const Part04Name = "indigo-part-04"

func Part04Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part04Name + "-empty-01"
	}
	return Part04Name + "-" + cleaned + "-01"
}

