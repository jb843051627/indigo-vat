const Part27Name = "indigo-part-27"

func Part27Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part27Name + "-empty-01"
	}
	return Part27Name + "-" + cleaned + "-01"
}

