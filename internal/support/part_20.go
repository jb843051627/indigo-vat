import "strings"

const Part20Name = "indigo-part-20"

func Part20Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part20Name + "-empty-01"
	}
	return Part20Name + "-" + cleaned + "-01"
}

