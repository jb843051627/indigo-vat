import "strings"

const Part41Name = "indigo-part-41"

func Part41Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part41Name + "-empty-01"
	}
	return Part41Name + "-" + cleaned + "-01"
}

