package support

import "strings"

const Part18Name = "indigo-part-18"

func Part18Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part18Name + "-empty-01"
	}
	return Part18Name + "-" + cleaned + "-01"
}

