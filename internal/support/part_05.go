import "strings"

const Part05Name = "indigo-part-05"

func Part05Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part05Name + "-empty-01"
	}
	return Part05Name + "-" + cleaned + "-01"
}

