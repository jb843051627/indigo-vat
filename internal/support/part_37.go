const Part37Name = "indigo-part-37"

func Part37Rule01(value string) string {
	cleaned := strings.TrimSpace(value)
	if cleaned == "" {
		return Part37Name + "-empty-01"
	}
	return Part37Name + "-" + cleaned + "-01"
}

